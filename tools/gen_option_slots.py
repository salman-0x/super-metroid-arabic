def main():
    rom = Rom.load(sys.argv[1])
    path = sys.argv[2]
    maps = {}
    slots = []
    for (m, r, (e0, e1), region, kind, align, text) in T:
        if m not in maps:
            maps[m] = O.load_map(rom, m)[0]
        w = maps[m]
        s = {"map": m, "row": r, "kind": kind, "span": [e0, e1], "region": list(region), "align": align, "text": text}
        if kind == "big":
            s["expect_top"] = [f"{x:03X}" for x in O._row(w, r, e0, e1)]
            s["expect_bottom"] = [f"{x:03X}" for x in O._row(w, r + 1, e0, e1)]
        else:
            s["expect"] = [f"{x:03X}" for x in O._row(w, r, e0, e1)]
        O.validate_slot(w, s)                      # fails loudly if my coordinates are wrong
        slots.append(s)
    doc = json.load(open(path, encoding="utf-8"))
    doc["_menus"]["options"] = {"_note": "slots generated by tools/gen_option_slots.py from the ORIGINAL ROM; edit 'text' here.",
                                "slots": slots}
    text = json.dumps(doc, ensure_ascii=False, indent=1)
    # keep arrays of plain numbers/strings on one line (tile-id lists, spans, rows/cols) so the file stays readable
    import re
    text = re.sub(r'\[\s+((?:"[^"\n]*"|-?\d+)(?:,\s+(?:"[^"\n]*"|-?\d+))*)\s+\]',
                  lambda m: "[" + re.sub(r",\s+", ", ", m.group(1)) + "]", text)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text + "\n")
    print(len(slots), "slots written to", path)


if __name__ == "__main__":
    main()
